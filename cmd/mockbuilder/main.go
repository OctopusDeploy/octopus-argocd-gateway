package main

import (
	"flag"
	"fmt"
	"go/types"
	"os"
	"path/filepath"
	"strings"

	"github.com/dave/jennifer/jen"
	"golang.org/x/tools/go/packages"
)

type interfaceMethod struct {
	Name    string
	Params  []paramInfo
	Results []paramInfo
}

type paramInfo struct {
	Name string
	Type string
}

func main() {
	source := flag.String("source", "", "Source file containing the interface")
	iface := flag.String("interface", "", "Interface name to generate mock for")
	dest := flag.String("destination", "", "Destination file for generated mock")
	pkg := flag.String("package", "mock", "Package name for generated code")
	flag.Parse()

	if *source == "" || *iface == "" || *dest == "" {
		fmt.Fprintln(
			os.Stderr,
			"Usage: mockbuilder -source=<file> -interface=<name> -destination=<file> [-package=<name>]",
		)
		os.Exit(1)
	}

	if err := generate(*source, *iface, *dest, *pkg); err != nil {
		fmt.Fprintf(os.Stderr, "Error: %v\n", err)
		os.Exit(1)
	}
}

func generate(source, ifaceName, dest, pkgName string) error {
	absSource, err := filepath.Abs(source)
	if err != nil {
		return fmt.Errorf("failed to get absolute path: %w", err)
	}

	methods, err := parseInterface(absSource, ifaceName)
	if err != nil {
		return fmt.Errorf("failed to parse interface: %w", err)
	}

	if err := generateCode(methods, ifaceName, dest, pkgName, source); err != nil {
		return fmt.Errorf("failed to generate code: %w", err)
	}

	return nil
}

func parseInterface(sourcePath, ifaceName string) ([]interfaceMethod, error) {
	cfg := &packages.Config{
		Mode: packages.NeedTypes | packages.NeedSyntax | packages.NeedImports | packages.NeedTypesInfo,
	}

	pkgs, err := packages.Load(cfg, "file="+sourcePath)
	if err != nil {
		return nil, fmt.Errorf("failed to load package: %w", err)
	}

	if len(pkgs) == 0 {
		return nil, fmt.Errorf("no packages found")
	}

	pkg := pkgs[0]
	if len(pkg.Errors) > 0 {
		return nil, fmt.Errorf("package errors: %v", pkg.Errors)
	}

	obj := pkg.Types.Scope().Lookup(ifaceName)
	if obj == nil {
		return nil, fmt.Errorf("interface %s not found", ifaceName)
	}

	ifaceType, ok := obj.Type().Underlying().(*types.Interface)
	if !ok {
		return nil, fmt.Errorf("%s is not an interface", ifaceName)
	}

	return extractMethods(ifaceType, pkg), nil
}

func extractMethods(iface *types.Interface, pkg *packages.Package) []interfaceMethod {
	var methods []interfaceMethod

	for i := 0; i < iface.NumMethods(); i++ {
		m := iface.Method(i)
		sig := m.Type().(*types.Signature)

		method := interfaceMethod{
			Name:    m.Name(),
			Params:  extractParams(sig.Params(), pkg),
			Results: extractParams(sig.Results(), pkg),
		}
		methods = append(methods, method)
	}

	return methods
}

func extractParams(tuple *types.Tuple, pkg *packages.Package) []paramInfo {
	var params []paramInfo
	for i := 0; i < tuple.Len(); i++ {
		v := tuple.At(i)
		params = append(params, paramInfo{
			Name: v.Name(),
			Type: types.TypeString(v.Type(), qualifier(pkg)),
		})
	}
	return params
}

func qualifier(pkg *packages.Package) types.Qualifier {
	return func(other *types.Package) string {
		if other == nil || other.Path() == pkg.PkgPath {
			return ""
		}
		return other.Name()
	}
}

func generateCode(methods []interfaceMethod, ifaceName, dest, pkgName, sourcePath string) error {
	f := jen.NewFile(pkgName)

	f.HeaderComment("Code generated by mockbuilder. DO NOT EDIT.")
	f.HeaderComment(fmt.Sprintf("Source: %s", sourcePath))

	mockName := "Mock" + ifaceName

	generateFuncTypes(f, methods)
	generateBuilderStruct(f, mockName)
	generateBuilderConstructor(f, mockName)
	generateWithMethods(f, methods, mockName)
	generateBuildMethod(f, mockName)

	if err := os.MkdirAll(filepath.Dir(dest), 0o755); err != nil {
		return fmt.Errorf("failed to create destination directory: %w", err)
	}

	return f.Save(dest)
}

func generateFuncTypes(f *jen.File, methods []interfaceMethod) {
	for _, m := range methods {
		typeName := m.Name + "Func"
		f.Type().Id(typeName).Func().ParamsFunc(func(g *jen.Group) {
			for _, p := range m.Params {
				g.Id(p.Name).Add(parseType(p.Type))
			}
		}).ParamsFunc(func(g *jen.Group) {
			for _, r := range m.Results {
				g.Add(parseType(r.Type))
			}
		})
	}
	f.Line()
}

func generateBuilderStruct(f *jen.File, mockName string) {
	f.Type().Id("Builder").StructFunc(func(g *jen.Group) {
		g.Id("mock").Op("*").Id(mockName)
	})
	f.Line()
}

func generateBuilderConstructor(f *jen.File, mockName string) {
	f.Func().Id("NewBuilder").Params(
		jen.Id("ctrl").Op("*").Qual("go.uber.org/mock/gomock", "Controller"),
	).Op("*").Id("Builder").Block(
		jen.Return(jen.Op("&").Id("Builder").Values(jen.Dict{
			jen.Id("mock"): jen.Id("New" + mockName).Call(jen.Id("ctrl")),
		})),
	)
	f.Line()
}

func generateWithMethods(f *jen.File, methods []interfaceMethod, mockName string) {
	for _, m := range methods {
		funcType := m.Name + "Func"

		f.Func().Params(jen.Id("b").Op("*").Id("Builder")).Id("With"+m.Name).
			Params(jen.Id("fn").Id(funcType)).
			Op("*").Id("Builder").
			Block(
				jen.Id("b").Dot("mock").Dot("EXPECT").Call().Dot(m.Name).CallFunc(func(g *jen.Group) {
					for range m.Params {
						g.Qual("go.uber.org/mock/gomock", "Any").Call()
					}
				}).Dot("DoAndReturn").Call(jen.Id("fn")).Dot("AnyTimes").Call(),
				jen.Return(jen.Id("b")),
			)
	}
	f.Line()
}

func generateBuildMethod(f *jen.File, mockName string) {
	f.Func().Params(jen.Id("b").Op("*").Id("Builder")).Id("Build").
		Params().
		Op("*").Id(mockName).
		Block(
			jen.Return(jen.Id("b").Dot("mock")),
		)
	f.Line()
}

func parseType(typeStr string) *jen.Statement {
	typeStr = strings.TrimSpace(typeStr)

	if strings.HasPrefix(typeStr, "*") {
		return jen.Op("*").Add(parseType(typeStr[1:]))
	}

	if strings.HasPrefix(typeStr, "[]") {
		return jen.Index().Add(parseType(typeStr[2:]))
	}

	if strings.HasPrefix(typeStr, "map[") {
		idx := findMatchingBracket(typeStr, 3)
		if idx > 0 {
			keyType := typeStr[4:idx]
			valueType := typeStr[idx+1:]
			return jen.Map(parseType(keyType)).Add(parseType(valueType))
		}
	}

	if strings.Contains(typeStr, ".") {
		parts := strings.SplitN(typeStr, ".", 2)
		pkgAlias := parts[0]
		typeName := parts[1]
		pkgPath := resolvePackagePath(pkgAlias)
		return jen.Qual(pkgPath, typeName)
	}

	return jen.Id(typeStr)
}

func findMatchingBracket(s string, start int) int {
	depth := 1
	for i := start + 1; i < len(s); i++ {
		if s[i] == '[' {
			depth++
		} else if s[i] == ']' {
			depth--
			if depth == 0 {
				return i
			}
		}
	}
	return -1
}

func resolvePackagePath(alias string) string {
	knownPackages := map[string]string{
		"context":     "context",
		"errors":      "errors",
		"v1alpha1":    "github.com/argoproj/argo-cd/v3/pkg/apis/application/v1alpha1",
		"application": "github.com/argoproj/argo-cd/v3/pkg/apiclient/application",
		"v1":          "k8s.io/api/core/v1",
		"argocd":      "github.com/OctopusDeploy/octopus-argocd-gateway/internal/argocd",
	}

	if path, ok := knownPackages[alias]; ok {
		return path
	}
	return alias
}
